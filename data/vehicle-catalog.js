export function vehicleFuelKey(fuel) {
  const value = String(fuel || '').toLocaleLowerCase('tr-TR');
  if (value.includes('belir') || value.includes('elektr')) return '';
  if (value.includes('motor') || value.includes('dizel')) return 'motorin';
  if (value.includes('lpg')) return 'lpg';
  return 'benzin';
}
